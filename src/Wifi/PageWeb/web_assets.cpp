void AddRoutesToServer(AsyncWebServer& server, const char* DefaultPage)
{
  // route par défaut
  server.on("/", HTTP_GET, [DefaultPage](AsyncWebServerRequest *request){
      request->redirect(DefaultPage);
  });

  // page non trouvée + portail captif
  server.onNotFound([DefaultPage](AsyncWebServerRequest *request){
    String url = request->url();
    if (url.indexOf("generate") != -1 || url.indexOf("gstatic") != -1) {
      Serial.printf("Portail Captif : Redirection de %s vers %s\n", url.c_str(), DefaultPage);
    } else {
      Serial.printf("Redirection standard de %s vers %s\n", url.c_str(), DefaultPage);
    }
    request->redirect(DefaultPage);
  });

  server.on("/favicon.ico", HTTP_GET, [](AsyncWebServerRequest *request){
    request->send(200, "image/x-icon", (const uint8_t*)WEB::favicon_ico, WEB::favicon_ico_len);
  });

  server.on("/style.css", HTTP_GET, [](AsyncWebServerRequest *request){
    request->send(200, "text/css", (const uint8_t*)WEB::style_css, WEB::style_css_len);
  });

  server.on("/Wifi.html", HTTP_GET, [](AsyncWebServerRequest *request){
    request->send(200, "text/html", (const uint8_t*)WEB::Wifi_html, WEB::Wifi_html_len);
  });

  server.on("/Wifi.js", HTTP_GET, [](AsyncWebServerRequest *request){
    request->send(200, "application/javascript", (const uint8_t*)WEB::Wifi_js, WEB::Wifi_js_len);
  });

}